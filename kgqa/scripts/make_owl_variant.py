"""Build the OWL variant of the alarm graph for the direction experiment.

The direction audit (direction_audit.py) found that most remaining errors put
the cause on the wrong side of net:causallyLinkedTo, and that K02 fails because
net:correlatedWith is stored one way only. This variant adds two axioms and
materialises what they entail, nothing else:

    net:causedBy        owl:inverseOf  net:causallyLinkedTo
    net:correlatedWith  a owl:SymmetricProperty

so "what caused X" can be written in the direction it is asked
(X net:causedBy ?c), and a correlation can be read from either end. Every
gold answer of the alarm benchmark is unchanged on the variant
(tests/test_owl_variant.py).

    python kgqa/scripts/make_owl_variant.py      # -> ontology/alarm_ontology_owl.ttl
"""

from __future__ import annotations

import argparse
from pathlib import Path

from rdflib import OWL, RDF, RDFS, Graph, Literal, Namespace

ROOT = Path(__file__).resolve().parents[2]
NET = Namespace("http://example.org/network#")


def owl_variant(src: Path) -> tuple[Graph, int]:
    g = Graph()
    g.parse(src, format="turtle")
    g.add((NET.causedBy, RDF.type, OWL.ObjectProperty))
    g.add((NET.causedBy, OWL.inverseOf, NET.causallyLinkedTo))
    g.add((NET.causedBy, RDFS.domain, NET.Alarm))
    g.add((NET.causedBy, RDFS.range, NET.Alarm))
    g.add((NET.causedBy, RDFS.label, Literal("caused by")))
    g.add((NET.causedBy, RDFS.comment,
           Literal("B caused by A: A causes B. Inverse of causally linked to.")))
    g.add((NET.correlatedWith, RDF.type, OWL.SymmetricProperty))
    added = 0
    for p, q in list(g.subject_objects(OWL.inverseOf)):
        for a, b in [(p, q), (q, p)]:
            for s, o in list(g.subject_objects(a)):
                if (o, b, s) not in g:
                    g.add((o, b, s)); added += 1
    for p in list(g.subjects(RDF.type, OWL.SymmetricProperty)):
        for s, o in list(g.subject_objects(p)):
            if (o, p, s) not in g:
                g.add((o, p, s)); added += 1
    return g, added


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default=str(ROOT / "ontology" / "alarm_ontology.ttl"))
    ap.add_argument("--out", default=str(ROOT / "ontology" / "alarm_ontology_owl.ttl"))
    args = ap.parse_args()
    g, added = owl_variant(Path(args.src))
    g.bind("net", NET)
    header = ("# GENERATED by kgqa/scripts/make_owl_variant.py from alarm_ontology.ttl.\n"
              "# Adds net:causedBy (owl:inverseOf net:causallyLinkedTo) and makes\n"
              f"# net:correlatedWith symmetric; {added} entailed triples materialised.\n\n")
    Path(args.out).write_text(header + g.serialize(format="turtle"))
    print(f"{args.out}: {len(g)} triples, {added} materialised")


if __name__ == "__main__":
    main()
